/** Traduce una clave e interpola {variables} */
function t(key, vars) {
  if (key == null) return '';
  const dict = I18N[currentLang] || {};
  let s = dict[key] ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// --- Traducción del HTML estático ---------------------------------------
const _i18nTextOrig = new WeakMap();
const _i18nHtmlOrig = new WeakMap();
const I18N_ATTRS = ['placeholder', 'title', 'alt'];

/**
 * Recorre el DOM y traduce nodos de texto y atributos cuyo texto original (en inglés)
 * exista en el diccionario. Los elementos con data-i18n-html="clave" se traducen
 * completos (para párrafos con marcado). Lo generado por JS ya usa t().
 */
function translateStatic(root = document.body) {
  if (!root) return;

  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    if (!_i18nHtmlOrig.has(el)) _i18nHtmlOrig.set(el, el.innerHTML);
    const key = el.dataset.i18nHtml;
    el.innerHTML = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || _i18nHtmlOrig.get(el);
  });

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => {
      const p = n.parentElement;
      if (!p || ['SCRIPT', 'STYLE'].includes(p.tagName) || p.closest('[data-i18n-html], [data-no-i18n]')) return NodeFilter.FILTER_REJECT;
      return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (!_i18nTextOrig.has(n)) _i18nTextOrig.set(n, n.nodeValue);
    const orig = _i18nTextOrig.get(n);
    const key = orig.trim().replace(/\s+/g, ' ');
    const tr = t(key);
    n.nodeValue = tr === key ? orig : orig.replace(orig.trim(), tr);
  }

  root.querySelectorAll(I18N_ATTRS.map(a => `[${a}]`).join(',')).forEach(el => {
    I18N_ATTRS.forEach(a => {
      if (!el.hasAttribute(a)) return;
      const ds = `i18nOrig${a[0].toUpperCase()}${a.slice(1)}`;
      if (!(ds in el.dataset)) el.dataset[ds] = el.getAttribute(a);
      el.setAttribute(a, t(el.dataset[ds]));
    });
  });
}

